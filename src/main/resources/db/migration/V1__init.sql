-- Baseline schema, matching exactly what Hibernate's ddl-auto=update generates for the
-- UrlMapping entity today (verified by dumping Hibernate's own create script before writing this).
-- Used only by the "prod" profile (file-based H2); local dev and tests keep ddl-auto=update.
create table url_mapping (
    id bigint generated by default as identity,
    short_code varchar(16) not null,
    original_url varchar(2048) not null,
    created_at timestamp(6) with time zone not null,
    click_count bigint not null,
    expires_at timestamp(6) with time zone,
    last_clicked_at timestamp(6) with time zone,
    primary key (id),
    constraint uk_url_mapping_short_code unique (short_code)
);
